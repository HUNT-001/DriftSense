class DocsError(Exception):
    """A rendering or validation problem with a human-readable location."""


class MissingSource(DocsError):
    """The referenced metric does not exist in an existing results file."""


# --------------------------------------------------------------------------- results


def results_model():
    """Return driftsense.contracts.ResultsFile (never redefined here)."""
    try:
        from driftsense.contracts import ResultsFile
    except ImportError:
        if str(ROOT) not in sys.path:
            sys.path.append(str(ROOT))
        try:
            from driftsense.contracts import ResultsFile
        except ImportError as exc:  # pragma: no cover - depends on environment
            raise DocsError(
                "cannot import driftsense.contracts.ResultsFile "
                "(install the repo with `pip install -e .` or set PYTHONPATH)"
            ) from exc
    return ResultsFile


def key_to_path(key: str) -> str:
    """'accuracy/g2' -> 'results/accuracy/g2.json' (canonical, repo-relative)."""
    return f"{RESULTS_PREFIX}{key}.json"


def path_to_key(path: str) -> str | None:
    if not path.startswith(RESULTS_PREFIX) or not path.endswith(".json"):
        return None
    return path[len(RESULTS_PREFIX) : -len(".json")]


class Results(dict):
    """key -> ResultsFile for every validated results file, plus ``raw``:
    key -> parsed JSON for EVERY results/**/*.json (ResultsFiles, plain JSON
    documents such as sealed/decisions.json, and *_meta.json sidecars). m()/n()/
    meta() read the ResultsFiles; q() (the A-grammar placeholder) reads ``raw``."""

    def __init__(self, *args: Any, raw: dict[str, Any] | None = None, **kw: Any):
        super().__init__(*args, **kw)
        self.raw: dict[str, Any] = dict(raw or {})


def is_plain_document(obj: Any) -> bool:
    """A results JSON that does not claim to be a ResultsFile: no ``metrics`` key and
    a schema_id other than driftsense.results/*. Examples: sealed/decisions.json,
    sealed/disclosures.json (schema driftsense.disclosures/1). Such files are read
    by q() only and are not validated against the ResultsFile contract. A file that
    looks like a ResultsFile but fails validation is still an error."""
    if not isinstance(obj, dict):
        return True
    sid = obj.get("schema_id")
    if "metrics" in obj or (isinstance(sid, str) and sid.startswith("driftsense.results")):
        return False
    return True


def load_results(results_dir: Path) -> tuple[Results, list[str]]:
    """Load and validate every results/**/*.json. Returns (Results, errors).

    Sidecars (``*_meta.json``, e.g. bench/cool_bench_meta.json written next to
    cool_bench.json by bench/cool/report.py) and plain JSON documents (see
    is_plain_document) are evidence, not ResultsFiles: they must parse as JSON but
    are not validated and cannot be referenced by m(); q() can read them."""
    out = Results()
    errors: list[str] = []
    files = sorted(results_dir.rglob("*.json")) if results_dir.is_dir() else []
    if not files:
        return out, errors
    model = results_model()
    for f in files:
        key = f.relative_to(results_dir).with_suffix("").as_posix()
        try:
            data = f.read_bytes()
            obj = json.loads(data)
        except (ValueError, OSError) as exc:
            kind = "sidecar is not valid JSON" if is_sidecar(f) else "invalid ResultsFile"
            errors.append(f"{f.as_posix()}: {kind}: {exc}")
            continue
        out.raw[key] = obj
        if is_sidecar(f) or is_plain_document(obj):
            continue
        try:
            out[key] = model.model_validate_json(data)
        except (ValueError, OSError) as exc:  # pydantic ValidationError
            first = str(exc).strip().splitlines()
            detail = "; ".join(line.strip() for line in first[:6])
            errors.append(f"{f.as_posix()}: invalid ResultsFile: {detail}")
    return out, errors


def dataset_of(results: Any, path: str) -> str | None:
    """Dataset label of the file a marker points to ('results/x.json'), or None."""
    key = path_to_key(path)
    if key is None:
        return None
    rf = results.get(key)
    if rf is not None:
        return rf.dataset
    doc = getattr(results, "raw", {}).get(key)
    if isinstance(doc, dict) and isinstance(doc.get("dataset"), str):
        return doc["dataset"]
    return None


def is_sidecar(path: Path) -> bool:
    return path.name.endswith("_meta.json")


def ci_verdict_of(metric: Any, null: float = 1.0) -> str:
    """Compare a metric's CI with a null value (1.0 for speed-ups).

    'higher'  - ci_low > null        'lower' - ci_high < null
    'includes' - the CI contains null (report as no measurable difference)
    'no_ci'   - no interval, or a degenerate one (ci_low == ci_high, one sample)"""
    lo, hi = metric.ci_low, metric.ci_high
    if lo is None or hi is None or lo == hi:
        return "no_ci"
    if lo > null:
        return "higher"
    if hi < null:
        return "lower"
    return "includes"


# --------------------------------------------------------------------------- formatting


def _num(v: float, decimals: int | None, grouping: bool = False) -> str:
    if decimals is None:  # raw
        if float(v).is_integer() and abs(v) < 1e15:
            s = str(int(v))
        else:
            s = repr(float(v))
    else:
        s = f"{v:,.{decimals}f}" if grouping else f"{v:.{decimals}f}"
    if s.startswith("-") and float(s.replace(",", "")) == 0.0:
        s = s[1:]
    return s


def _with_affix(v: float, decimals, grouping, prefix: str) -> str:
    s = _num(v, decimals, grouping)
    if s.startswith("-"):
        return "-" + prefix + s[1:]
    return prefix + s


def resolve_fmt(fmt: str | None, unit: str) -> str:
    if fmt is None:
        return UNIT_DEFAULT_FMT.get(unit.strip().lower(), "raw")
    if fmt not in FORMATS:
        raise DocsError(f"unknown fmt={fmt!r}; choose from {', '.join(FORMATS)}")
    return fmt


def format_number(
    value: float,
    unit: str,
    fmt: str,
    ci: tuple[float, float] | None = None,
) -> str:
    """Format a value (and optional 95% CI) exactly as it must appear in the docs."""
    vals = [value] + (list(ci) if ci else [])
    for v in vals:
        if not math.isfinite(v):
            raise DocsError(f"non-finite value {v!r} cannot be rendered")
    u = unit.strip().lower()
    prefix, suffix, grouping = "", "", False
    if fmt == "raw":
        decimals = None
    elif fmt == "int":
        decimals, grouping = 0, True
    elif fmt in ("f1", "f2", "f3"):
        decimals = int(fmt[1])
    elif fmt == "pct":
        k = 1.0 if u in PCT_UNITS else 100.0
        vals = [v * k for v in vals]
        decimals, suffix = 1, "%"
    elif fmt == "ms":
        if u not in MS_SCALE:
            raise DocsError(f"fmt='ms' needs unit ms/s/us, metric unit is {unit!r}")
        vals = [v * MS_SCALE[u] for v in vals]
        a = abs(vals[0])
        decimals, suffix = (0 if a >= 100 else 1 if a >= 10 else 2), " ms"
    elif fmt == "x":
        a = abs(vals[0])
        decimals, suffix = (1 if a >= 10 else 2 if a >= 2 else 3), "×"
    elif fmt == "usd":
        a = abs(vals[0])
        # >= $1: cents; below: three significant figures (min. two decimals)
        decimals = 2 if a >= 1 or a == 0 else max(2, 2 - math.floor(math.log10(a)))
        prefix, grouping = "$", True
    else:
        raise DocsError(f"unknown fmt={fmt!r}; choose from {', '.join(FORMATS)}")
    text = _with_affix(vals[0], decimals, grouping, prefix) + suffix
    if ci:
        lo = _with_affix(vals[1], decimals, grouping, prefix)
        hi = _with_affix(vals[2], decimals, grouping, prefix) + suffix
        text += f" (95% CI {lo}–{hi})"
    return text


# --------------------------------------------------------------------------- markers


@dataclass(frozen=True)
class Ref:
    """One provenance reference: what was rendered and from where."""

    key: str
    field: str  # metric name, or "@<meta path>"
    sub: str = "value"  # "value" or "n" (metrics only)
    fmt: str | None = None
    ci: bool = False
    label: bool = True
    q: bool = False  # A-grammar placeholder: field is a JSON path, bare text, no label
    code: bool = False  # q only: the value is wrapped in an inline code span

    @property
    def is_meta(self) -> bool:
        return not self.q and self.field.startswith("@")

    @property
    def path(self) -> str:
        return key_to_path(self.key)

    def marker(self) -> str:
        if self.q:
            opts = ["q"]
            if self.fmt:
                opts.append(f"fmt={self.fmt}")
            if self.code:
                opts.append("code")
            return f"<!--src:{self.path}#{self.field} {' '.join(opts)}-->"
        opts = []
        if self.sub != "value":
            opts.append(f"field={self.sub}")
        if self.fmt:
            opts.append(f"fmt={self.fmt}")
        if self.ci:
            opts.append("ci")
        if not self.label and not self.is_meta:
            opts.append("nolabel")
        tail = (" " + " ".join(opts)) if opts else ""
        return f"<!--src:{self.path}#{self.field}{tail}-->"

    def missing(self) -> str:
        return f"{MISSING_OPEN}{self.path}#{self.field}{MISSING_CLOSE}"


def parse_marker(m: re.Match) -> Ref:
    key = path_to_key(m.group("path"))
    if key is None:
        raise DocsError(f"marker path {m.group('path')!r} is not results/<key>.json")
    opts: dict[str, str] = {}
    for tok in m.group("opts").split():
        k, _, v = tok.partition("=")
        opts[k] = v
    if "q" in opts:
        unknown = set(opts) - {"q", "fmt", "code"}
        if unknown:
            raise DocsError(f"unknown q-marker option(s) {sorted(unknown)}")
        return Ref(
            key=key,
            field=m.group("field"),
            fmt=opts.get("fmt") or None,
            label=False,
            q=True,
            code="code" in opts,
        )
    unknown = set(opts) - {"field", "fmt", "ci", "nolabel"}
    if unknown:
        raise DocsError(f"unknown marker option(s) {sorted(unknown)}")
    return Ref(
        key=key,
        field=m.group("field"),
        sub=opts.get("field", "value"),
        fmt=opts.get("fmt") or None,
        ci="ci" in opts,
        label="nolabel" not in opts,
    )


def meta_value(rf: Any, path: str, fmt: str | None = None) -> str:
    """Render a metadata field of a ResultsFile (no label, exact string)."""
    if fmt not in META_FORMATS:
        raise DocsError(f"meta fmt must be one of {META_FORMATS}, got {fmt!r}")
    if path.startswith("env."):
        name = path[4:]
        if name not in type(rf.env).model_fields:
            raise DocsError(f"unknown meta field {path!r}")
        v = getattr(rf.env, name)
    elif path in META_FIELDS:
        v = getattr(rf, path)
    else:
        allowed = ", ".join(META_FIELDS) + ", env.<field>"
        raise DocsError(f"unknown meta field {path!r}; allowed: {allowed}")
    if v is None:
        raise DocsError(f"meta field {path!r} is null in this results file")
    if path == "created_at":
        return v.date().isoformat() if fmt == "date" else v.isoformat()
    if fmt == "date":
        raise DocsError("fmt='date' only applies to created_at")
    if isinstance(v, bool):
        return "true" if v else "false"
    return str(v)


def render_ref(ref: Ref, rf: Any) -> str:
    """Visible text for a reference (without the marker). Raises DocsError."""
    if ref.is_meta:
        return meta_value(rf, ref.field[1:], ref.fmt)
    metric = rf.metrics.get(ref.field)
    if metric is None:
        avail = ", ".join(sorted(rf.metrics)) or "(none)"
        raise MissingSource(f"metric {ref.field!r} not in {ref.path} (available: {avail})")
    if ref.sub == "n":
        if metric.n is None:
            raise DocsError(f"metric {ref.field!r} in {ref.path} has no n")
        text = format_number(float(metric.n), "count", ref.fmt or "int")
    elif ref.sub == "value":
        ci = None
        if ref.ci:
            if metric.ci_low is None or metric.ci_high is None:
                raise DocsError(f"ci=true but metric {ref.field!r} in {ref.path} has no ci_low/ci_high")
            ci = (metric.ci_low, metric.ci_high)
        text = format_number(metric.value, metric.unit, resolve_fmt(ref.fmt, metric.unit), ci)
    else:
        raise DocsError(f"unknown marker field={ref.sub!r}")
    label = DATASET_LABELS.get(rf.dataset)
    if ref.label and label:
        text += f" [{label}]"
    return text


# --------------------------------------------------------------------------- q(): JSON paths

_JP_TOKEN = re.compile(
    r"""\[\s*'(?P<sq>[^']*)'\s*\]|\[\s*"(?P<dq>[^"]*)"\s*\]|\[(?P<idx>\d+)\]"""
    r"|(?P<dot>\.)|(?P<name>[^.\[\]\s]+)"
)


def parse_jsonpath(path: str) -> list[str | int]:
    """metrics['top1.pooled'].value -> ['metrics', 'top1.pooled', 'value'];
    disclosures.2.what -> ['disclosures', '2', 'what'] (digits index lists);
    [3] -> 3. Raises DocsError on anything else."""
    if not path or re.search(r"\s|-->|<!--", path):
        raise DocsError(f"bad JSON path {path!r} (no whitespace or comment delimiters)")
    out: list[str | int] = []
    pos, expect_seg = 0, True
    while pos < len(path):
        m = _JP_TOKEN.match(path, pos)
        if m is None:
            raise DocsError(f"bad JSON path {path!r} at offset {pos}")
        if m.group("dot") is not None:
            if expect_seg:
                raise DocsError(f"bad JSON path {path!r}: empty segment at offset {pos}")
            expect_seg = True
        elif m.group("idx") is not None:
            out.append(int(m.group("idx")))
            expect_seg = False
        else:
            if not expect_seg and m.group("name") is not None:
                raise DocsError(f"bad JSON path {path!r} at offset {pos}")
            name = next(g for g in (m.group("sq"), m.group("dq"), m.group("name")) if g is not None)
            out.append(name)
            expect_seg = False
        pos = m.end()
    if expect_seg:
        raise DocsError(f"bad JSON path {path!r}: ends with '.'")
    return out


def resolve_jsonpath(doc: Any, path: str, where: str) -> tuple[Any, Any]:
    """Return (value, parent container) for a JSON path into a parsed document."""
    cur, parent = doc, None
    for seg in parse_jsonpath(path):
        parent = cur
        if isinstance(cur, list):
            if isinstance(seg, str) and not seg.isdigit():
                raise MissingSource(f"{where}: {path!r}: {seg!r} is not a list index")
            i = int(seg)
            if not 0 <= i < len(cur):
                raise MissingSource(f"{where}: {path!r}: index {i} out of range (length {len(cur)})")
            cur = cur[i]
        elif isinstance(cur, dict):
            if str(seg) not in cur:
                avail = ", ".join(sorted(map(str, cur))[:40]) or "(none)"
                raise MissingSource(f"{where}: {path!r}: key {str(seg)!r} not found (available: {avail})")
            cur = cur[str(seg)]
        else:
            raise MissingSource(f"{where}: {path!r}: cannot descend into a {type(cur).__name__}")
    return cur, parent


def format_q(value: Any, fmt: str | None, unit: str = "") -> str:
    """Display text for one A-grammar placeholder value (bare number, no label)."""
    if fmt is None:
        if isinstance(value, bool):
            return "true" if value else "false"
        if isinstance(value, str):
            if "\n" in value or "<!--" in value or "-->" in value:
                raise DocsError("string spans lines or contains a comment delimiter")
            return value
        if isinstance(value, int):
            return str(value)
        if isinstance(value, float):
            if not math.isfinite(value):
                raise DocsError(f"non-finite value {value!r} cannot be rendered")
            return _num(value, None)
        if value is None:
            raise DocsError("value is null")
        raise DocsError(f"value is a JSON {type(value).__name__}; point the path at a scalar")
    if fmt not in Q_FORMATS:
        raise DocsError(f"unknown placeholder fmt {fmt!r}; choose from {', '.join(Q_FORMATS)}")
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        raise DocsError(f"fmt {fmt!r} needs a number, got {type(value).__name__}")
    v = float(value)
    if not math.isfinite(v):
        raise DocsError(f"non-finite value {v!r} cannot be rendered")
    u = (unit or "").strip().lower()
    grouping = False
    if fmt in ("pct", "pct0", "pct2"):
        v *= 1.0 if u in PCT_UNITS else 100.0
        decimals = {"pct": 1, "pct0": 0, "pct2": 2}[fmt]
    elif fmt == "ms0":
        if u and u not in MS_SCALE:
            raise DocsError(f"fmt 'ms0' needs a time unit, metric unit is {unit!r}")
        v *= MS_SCALE.get(u, 1.0)
        decimals = 0
    elif fmt == "x1":
        decimals = 1
    elif fmt == "nm3":
        decimals = 3
    elif fmt == "g":
        decimals, grouping = 0, True
    elif fmt == "int":
        decimals = 0
    else:  # f1 f2 f3
        decimals = int(fmt[1])
    return _num(v, decimals, grouping)


def render_q(ref: Ref, doc: Any) -> str:
    """Visible text (without marker) for a q() reference into a parsed JSON doc."""
    value, parent = resolve_jsonpath(doc, ref.field, ref.path)
    unit = parent.get("unit", "") if isinstance(parent, dict) else ""
    try:
        text = format_q(value, ref.fmt, unit if isinstance(unit, str) else "")
    except DocsError as exc:
        raise DocsError(f"{ref.path}#{ref.field}: {exc}") from None
    return f"`{text}`" if ref.code else text


def source_exists(ref: Ref, results: Any) -> bool:
    if ref.q:
        return ref.key in getattr(results, "raw", {})
    return ref.key in results


def render_any(ref: Ref, results: Any) -> str:
    """render_ref / render_q against a Results index. The source file must exist."""
    if ref.q:
        return render_q(ref, results.raw[ref.key])
    return render_ref(ref, results[ref.key])


# --------------------------------------------------------------------------- sentences


def fenced_lines(lines: list[str]) -> list[bool]:
    """True for lines inside (or delimiting) fenced code blocks."""
    out, inside = [], False
    for line in lines:
        if FENCE_RE.match(line):
            out.append(True)
            inside = not inside
        else:
            out.append(inside)
    return out


_LIST_ITEM = re.compile(r"^\s*(?:[-*+]|\d+[.)])\s")
_SENT_END = re.compile(r"[.!?](?=\s)")


def _units(text: str) -> list[tuple[int, int]]:
    """Split markdown into sentence-bearing units (paragraphs, list items,
    headings, table cells), as absolute (start, end) offsets."""
    units: list[tuple[int, int]] = []
    lines = text.split("\n")
    code = fenced_lines(lines)
    cur: list[int] | None = None
    pos = 0
    for line, is_code in zip(lines, code, strict=True):
        s, e = pos, pos + len(line)
        pos = e + 1
        stripped = line.strip()
        if is_code or not stripped:
            if cur:
                units.append((cur[0], cur[1]))
            cur = None
            continue
        if stripped.startswith(("|", "#")):
            if cur:
                units.append((cur[0], cur[1]))
            cur = None
            if stripped.startswith("|"):
                cs = s
                for i, ch in enumerate(line + "|"):
                    if ch == "|":
                        if s + i > cs:
                            units.append((cs, s + i))
                        cs = s + i + 1
            else:
                units.append((s, e))
            continue
        if _LIST_ITEM.match(line):
            if cur:
                units.append((cur[0], cur[1]))
            cur = [s, e]
            continue
        if cur:
            cur[1] = e
        else:
            cur = [s, e]
    if cur:
        units.append((cur[0], cur[1]))
    return units


def dev_sealed_violations(text: str, dataset_of: Callable[[str], str | None]) -> list[tuple[int, str]]:
    """Find markers sourced from dataset='dev' that share a sentence with the word
    'sealed' (any case). Returns (line, message). dataset_of maps a marker path
    ('results/x.json') to its dataset or None."""
    line_starts = [0] + [i + 1 for i, ch in enumerate(text) if ch == "\n"]
    found: list[tuple[int, str]] = []
    for us, ue in _units(text):
        seg = text[us:ue]
        bounds = [0] + [m.end() for m in _SENT_END.finditer(seg)] + [len(seg)]
        for a, b in itertools.pairwise(bounds):
            sent = seg[a:b]
            markers = list(MARKER_RE.finditer(sent))
            if not markers:
                continue
            plain = COMMENT_RE.sub(" ", sent)
            if not re.search(r"\bsealed\b", plain, re.IGNORECASE):
                continue
            for mk in markers:
                if dataset_of(mk.group("path")) == "dev":
                    off = us + a + mk.start()
                    line = bisect.bisect_right(line_starts, off)
                    found.append(
                        (
                            line,
                            (
                                f"DEV-sourced number ({mk.group('path')}#"
                                f"{mk.group('field')}) in a sentence that says 'sealed'"
                            ),
                        )
                    )
    return found


def read_text(path: Path) -> str:
    return path.read_bytes().decode("utf-8").replace("\r\n", "\n")


def is_generated(text: str) -> bool:
    return text.startswith(GENERATED_PREFIX)


def dumps_json(obj: Any) -> str:
    return json.dumps(obj, indent=2, sort_keys=True, ensure_ascii=False)
