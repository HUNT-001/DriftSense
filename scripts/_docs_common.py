def utf8_stdio() -> None:
    """Make stdout/stderr UTF-8 so docs text (×, ⟨, superscripts) prints on
    Windows consoles (cp1252) instead of raising UnicodeEncodeError."""
    for stream in (sys.stdout, sys.stderr):
        if hasattr(stream, "reconfigure"):
            stream.reconfigure(encoding="utf-8", errors="replace")


